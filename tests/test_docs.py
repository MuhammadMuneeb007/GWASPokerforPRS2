"""The documentation must describe the program that actually exists.

Hand-written flag tables rot silently: an option is added, the page is not
touched, and the site confidently documents something else. These tests read the
CLI's real signatures and check the published pages against them.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
DOCS = REPO / "docs"
MKDOCS = REPO / "mkdocs.yml"

COMMANDS = ("search", "probe", "assess", "scan", "download", "extract", "run", "benchmark")

#: Options every command inherits. They are documented once, in a shared table,
#: rather than repeated under all eight commands.
SHARED_FLAGS = frozenset(
    {"--config", "--failure-log", "--verbose", "--quiet", "--help", "-v", "-q"}
)


def flags_of(command: str) -> set[str]:
    """Every long option the command actually declares.

    Read from Click's parameter objects, not from rendered ``--help``. Rich
    truncates long option names in its output -- ``--no-check-files`` becomes
    ``--no-check-fil...`` -- by an amount that varies with the Rich version, so
    a test that parsed the rendering passed locally and failed on CI.
    """
    import typer.main

    from gwaspoker.cli import app

    subcommand = typer.main.get_command(app).commands[command]
    names = {
        opt
        for param in subcommand.params
        for opt in (*param.opts, *param.secondary_opts)
        if opt.startswith("--")
    }
    return names - SHARED_FLAGS


@pytest.fixture(scope="module")
def cli_reference() -> str:
    path = DOCS / "cli-reference.md"
    assert path.exists(), "run `python docs/generate_cli_reference.py`"
    return path.read_text(encoding="utf-8")


# ======================================================================
# The site is complete and internally consistent
# ======================================================================


def test_every_nav_page_exists() -> None:
    """A nav entry pointing at a missing file breaks the build."""
    nav = MKDOCS.read_text(encoding="utf-8")
    pages = re.findall(r":\s*([\w-]+\.md)\s*$", nav, flags=re.MULTILINE)
    assert pages, "no nav pages were parsed out of mkdocs.yml"
    missing = [p for p in pages if not (DOCS / p).exists()]
    assert not missing, f"nav references missing pages: {missing}"


def test_every_docs_page_is_in_the_nav() -> None:
    """An unreferenced page is invisible on the site -- usually a rename left over."""
    nav = MKDOCS.read_text(encoding="utf-8")
    on_disk = {p.name for p in DOCS.glob("*.md")}
    unreferenced = sorted(name for name in on_disk if name not in nav)
    assert not unreferenced, f"pages not reachable from the nav: {unreferenced}"


def test_internal_links_resolve() -> None:
    """A link to a page that no longer exists is a dead end on the site."""
    broken: list[str] = []
    for page in DOCS.glob("*.md"):
        for target in re.findall(
            r"\]\(([\w./-]+\.md)(?:#[\w-]+)?\)", page.read_text(encoding="utf-8")
        ):
            if not (page.parent / target).resolve().exists():
                broken.append(f"{page.name} -> {target}")
    assert not broken, f"broken internal links: {broken}"


