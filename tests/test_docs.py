def test_documented_failure_categories_exist() -> None:
    """Every category named in failures.md must be a real enum member."""
    from gwaspoker.failures import FailureCategory

    real = {c.value for c in FailureCategory}
    page = (DOCS / "failures.md").read_text(encoding="utf-8")
    # Anchored to a letter so the exit-code table (`0`, `1`, `2`) is not read
    # as a list of category names.
    named = set(re.findall(r"^\| `([a-z][a-z0-9_]+)` \|", page, flags=re.MULTILINE))
    invented = sorted(named - real)
    assert not invented, f"failures.md names categories that do not exist: {invented}"


def test_every_failure_category_is_documented() -> None:
    from gwaspoker.failures import FailureCategory

    page = (DOCS / "failures.md").read_text(encoding="utf-8")
    missing = sorted(c.value for c in FailureCategory if f"`{c.value}`" not in page)
    assert not missing, f"undocumented failure categories: {missing}"


def test_documented_config_settings_exist() -> None:
    """configuration.md must not describe settings the dataclass does not have."""
    import dataclasses

    from gwaspoker.config import GWASPokerConfig

    real = {f.name for f in dataclasses.fields(GWASPokerConfig)}
    page = (DOCS / "configuration.md").read_text(encoding="utf-8")
    # Anchored to a letter so numeric first cells elsewhere on the page are not
    # read as setting names.
    named = set(re.findall(r"^\| `([a-z][a-z0-9_]+)` \|", page, flags=re.MULTILINE))
    invented = sorted(named - real)
    assert not invented, f"configuration.md names settings that do not exist: {invented}"


def test_published_test_counts_are_true() -> None:
    """Docs state how many tests there are; the number must be the real one.

    A count in prose rots the moment a test is added, and a rotted count in the
    one place a reader checks credibility is worse than no count at all. This
    fails when they diverge, so updating the docs is part of adding a test.
    """
    collected = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "--collect-only"],
        cwd=REPO,
        capture_output=True,
        text=True,
        encoding="utf-8",
        env=dict(os.environ, PYTHONIOENCODING="utf-8"),
    ).stdout
    match = re.search(r"(\d+)/\d+ tests collected|^(\d+) tests collected", collected, re.MULTILINE)
    assert match, "could not read the collected count from pytest"
    total = match.group(1) or match.group(2)

    for page in ("index.md", "architecture.md", "reproducibility.md"):
        text = (DOCS / page).read_text(encoding="utf-8")
        for stale in re.findall(r"\b(\d{3})\b(?= unit tests| \| none)", text):
            assert stale == total, f"{page} says {stale} tests, pytest collects {total}"
    assert f"<strong>{total}</strong>" in (DOCS / "index.md").read_text(encoding="utf-8")
