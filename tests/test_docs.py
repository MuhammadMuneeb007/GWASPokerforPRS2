def test_every_command_has_a_section(cli_reference: str) -> None:
    missing = [c for c in COMMANDS if f"## `{c}`" not in cli_reference]
    assert not missing, f"commands with no section in cli-reference.md: {missing}"


@pytest.mark.parametrize("command", COMMANDS)
def test_every_flag_is_documented(command: str, cli_reference: str) -> None:
    """The guard that matters: a new option must reach the published page.

    `cli-reference.md` is generated by `docs/generate_cli_reference.py`. If this
    fails, the generator has not been re-run since the CLI changed.
    """
    section = cli_reference.split(f"## `{command}`", 1)[-1].split("\n## ", 1)[0]
    undocumented = sorted(flag for flag in flags_of(command) if f"`{flag}`" not in section)
    assert not undocumented, (
        f"`{command}` has undocumented flags: {undocumented}. "
        "Re-run: python docs/generate_cli_reference.py"
    )


def test_the_reference_is_current(cli_reference: str) -> None:
    """Regenerating must be a no-op, or the committed page is stale."""
    from gwaspoker import __version__

    assert f"**{__version__}**" in cli_reference, (
        "cli-reference.md was generated for a different version. "
        "Re-run: python docs/generate_cli_reference.py"
    )


