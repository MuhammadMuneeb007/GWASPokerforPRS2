def test_confusion_matrix_arithmetic() -> None:
    matrix = ConfusionMatrix(true_positive=8, false_positive=2, true_negative=7, false_negative=3)
    assert matrix.precision == pytest.approx(0.8)
    assert matrix.recall == pytest.approx(8 / 11)
    assert matrix.specificity == pytest.approx(7 / 9)
    assert matrix.accuracy == pytest.approx(15 / 20)
    assert matrix.f1 == pytest.approx(2 * 0.8 * (8 / 11) / (0.8 + 8 / 11))
    assert matrix.false_positive_rate == pytest.approx(2 / 9)


def test_undefined_metrics_are_none_not_zero() -> None:
    """'No positive cases' and 'recall is zero' are different statements."""
    matrix = ConfusionMatrix(true_negative=5)
    assert matrix.recall is None
    assert matrix.precision is None
    assert matrix.specificity == 1.0


def test_confusion_matrix_add() -> None:
    matrix = ConfusionMatrix()
    matrix.add(True, True)
    matrix.add(True, False)
    matrix.add(False, True)
    matrix.add(False, False)
    assert (matrix.true_positive, matrix.false_positive) == (1, 1)
    assert (matrix.false_negative, matrix.true_negative) == (1, 1)


def test_header_row_accuracy() -> None:
    result = header_row_accuracy([0, 2, 5, None], [0, 2, 3, 1])
    assert result["hits"] == 2
    assert result["n"] == 4
    assert result["rate"] == pytest.approx(0.5)


def test_header_row_accuracy_skips_unlabelled_rows() -> None:
    result = header_row_accuracy([0, 1], [0, None])
    assert result["n"] == 1


def test_exact_ordered_header_match_is_order_sensitive() -> None:
    """Set comparison would call these identical; they are not."""
    predicted = [("CHR", "POS", "SNP")]
    actual = [("POS", "CHR", "SNP")]
    assert exact_ordered_header_match(predicted, actual)["rate"] == 0.0
    assert exact_ordered_header_match(actual, actual)["rate"] == 1.0


def test_exact_ordered_header_match_case_insensitive_by_default() -> None:
    predicted = [("chr", "pos")]
    actual = [("CHR", "POS")]
    assert exact_ordered_header_match(predicted, actual)["rate"] == 1.0
    assert exact_ordered_header_match(predicted, actual, case_sensitive=True)["rate"] == 0.0


def test_missing_prediction_counts_as_a_miss() -> None:
    assert exact_ordered_header_match([None], [("CHR",)])["rate"] == 0.0


def test_column_set_metrics_use_multiset_semantics() -> None:
    """Duplicated column names must not be silently collapsed."""
    metrics = ColumnSetMetrics()
    metrics.add(["p", "p", "chr"], ["p", "chr"])
    assert metrics.true_positive == 2
    assert metrics.false_positive == 1  # the extra 'p'
    assert metrics.false_negative == 0


def test_column_set_metrics_precision_recall_f1() -> None:
    metrics = ColumnSetMetrics()
    metrics.add(["a", "b", "c"], ["a", "b", "d"])
    assert metrics.true_positive == 2
    assert metrics.precision == pytest.approx(2 / 3)
    assert metrics.recall == pytest.approx(2 / 3)
    assert metrics.f1 == pytest.approx(2 / 3)


def test_mapping_accuracy() -> None:
    predicted = [{"CHR": "chromosome", "P": "unknown"}]
    actual = [{"CHR": "chromosome", "P": "p_value"}]
    result = mapping_accuracy(predicted, actual)
    assert result["columns_compared"] == 2
    assert result["correct"] == 1
    assert result["accuracy"] == pytest.approx(0.5)
    assert result["predicted_unknown"] == 1
    assert result["per_concept"]["p_value"]["accuracy"] == 0.0


def test_mapping_accuracy_counts_a_missing_prediction_as_unknown() -> None:
    result = mapping_accuracy([{}], [{"CHR": "chromosome"}])
    assert result["predicted_unknown"] == 1
    assert result["accuracy"] == 0.0


def test_readiness_confusion_ready_is_positive() -> None:
    predicted = ["READY", "READY", "NOT_READY", "PARTIAL"]
    actual = ["READY", "NOT_READY", "NOT_READY", "READY"]
    matrix = readiness_confusion(predicted, actual)
    assert matrix.true_positive == 1
    assert matrix.false_positive == 1  # said READY, was not
    assert matrix.false_negative == 1  # said PARTIAL, was READY
    assert matrix.true_negative == 1


def test_readiness_confusion_lenient_positive_set() -> None:
    predicted = ["PARTIAL"]
    actual = ["READY"]
    lenient = readiness_confusion(
        predicted, actual, positive_labels=frozenset({"READY", "PARTIAL"})
    )
    assert lenient.true_positive == 1


def test_multiclass_agreement() -> None:
    result = multiclass_agreement(["READY", "PARTIAL"], ["READY", "NOT_READY"])
    assert result["agreement"]["rate"] == pytest.approx(0.5)
    assert result["confusion"]["NOT_READY"]["PARTIAL"] == 1


def test_transfer_metrics() -> None:
    metrics = TransferMetrics()
    metrics.add(probe_bytes=262144, api_bytes=700, full_size=1_000_000_000, probe_latency=1.5)
    metrics.add(probe_bytes=262144, api_bytes=700, full_size=2_000_000_000, probe_latency=2.5)
    payload = metrics.to_dict()

    assert payload["files"] == 2
    assert payload["total_bytes_transferred"] == 2 * 262144 + 2 * 700
    assert payload["percentage_transfer_reduction"] > 99.9
    assert payload["mean_probe_latency_seconds"] == pytest.approx(2.0)
    assert payload["median_probe_latency_seconds"] == pytest.approx(2.0)


def test_transfer_metrics_with_no_data() -> None:
    payload = TransferMetrics().to_dict()
    assert payload["files"] == 0
    assert payload["percentage_transfer_reduction"] is None
    assert payload["mean_probe_bytes"] is None


