def test_empty_manifest_is_flagged() -> None:
    assert validate_manifest([]) == ["The manifest is empty."]


def test_manifest_without_ground_truth_is_flagged() -> None:
    problems = validate_manifest([_row(study_accession="GCST1", predicted_prs_ready="READY")])
    assert any("No row carries ground truth" in p for p in problems)


def test_invalid_ground_truth_verdict_is_flagged() -> None:
    problems = validate_manifest(
        [_row(study_accession="GCST1", ground_truth_prs_ready="probably fine")]
    )
    assert any("is not one of" in p for p in problems)


def test_identical_prediction_and_truth_is_flagged_as_circular() -> None:
    """The ground truth must be curated independently of GWASPoker.

    If every labelled row's ground_truth_header equals its predicted_header,
    the labels were almost certainly machine-generated by the parser under
    test, and any metric computed from them is meaningless.
    """
    rows = [
        _row(
            study_accession=f"GCST{i}",
            predicted_header="CHR\tPOS\tSNP",
            ground_truth_header="CHR\tPOS\tSNP",
        )
        for i in range(4)
    ]
    problems = validate_manifest(rows)
    assert any("circular" in p for p in problems)


def test_independently_curated_labels_are_not_flagged() -> None:
    rows = [
        _row(study_accession="GCST1", predicted_header="CHR\tPOS", ground_truth_header="CHR\tPOS"),
        _row(study_accession="GCST2", predicted_header="CHR\tBP", ground_truth_header="CHR\tPOS"),
        _row(study_accession="GCST3", predicted_header="A\tB", ground_truth_header="A\tB"),
    ]
    problems = validate_manifest(rows)
    assert not any("circular" in p for p in problems)


