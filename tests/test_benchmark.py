"""Benchmark manifest parsing, metric computation and the circularity guard.

The most important test here is
:func:`test_identical_prediction_and_truth_is_flagged_as_circular`. Scoring a
parser against labels the same parser produced measures nothing, and the
evaluator has to say so rather than emit a flattering 100%.
"""

from __future__ import annotations

import pytest

from gwaspoker.benchmark.manifest import (
    MANIFEST_COLUMNS,
    ManifestRow,
    blank_row,
    format_header,
    format_mapping,
    read_manifest,
    validate_manifest,
    write_manifest,
)
from gwaspoker.benchmark.metrics import (
    ColumnSetMetrics,
    ConfusionMatrix,
    TransferMetrics,
    exact_ordered_header_match,
    header_row_accuracy,
    mapping_accuracy,
    multiclass_agreement,
    readiness_confusion,
)


def _row(**kwargs) -> ManifestRow:
    data = dict.fromkeys(MANIFEST_COLUMNS, "")
    data.update({k: str(v) for k, v in kwargs.items()})
    return ManifestRow(data)


# ----------------------------------------------------------------------
# Manifest parsing
# ----------------------------------------------------------------------


def test_blank_row_has_every_column() -> None:
    row = blank_row("GCST1", "migraine")
    assert set(row.data) == set(MANIFEST_COLUMNS)
    assert row.accession == "GCST1"


def test_header_cell_round_trip() -> None:
    header = ("CHR", "POS", "SNP", "A1")
    row = _row(predicted_header=format_header(header))
    assert row.header("predicted_header") == header


def test_header_order_is_preserved() -> None:
    row = _row(predicted_header="P\tCHR\tBP")
    assert row.header("predicted_header") == ("P", "CHR", "BP")


def test_header_cell_accepts_comma_separation() -> None:
    row = _row(ground_truth_header="CHR,POS,SNP")
    assert row.header("ground_truth_header") == ("CHR", "POS", "SNP")


def test_mapping_cell_round_trip() -> None:
    mapping = {"CHR": "chromosome", "P": "p_value"}
    row = _row(predicted_mapping=format_mapping(mapping))
    assert row.mapping("predicted_mapping") == mapping


def test_verdict_normalisation() -> None:
    assert _row(predicted_prs_ready="ready").verdict("predicted_prs_ready") == "READY"
    assert _row(predicted_prs_ready="not ready").verdict("predicted_prs_ready") == "NOT_READY"
    assert _row(predicted_prs_ready="yes").verdict("predicted_prs_ready") == "READY"
    assert _row(predicted_prs_ready="no").verdict("predicted_prs_ready") == "NOT_READY"
    assert _row(predicted_prs_ready="nonsense").verdict("predicted_prs_ready") is None


def test_empty_cells_read_as_none() -> None:
    row = _row(probe_bytes="")
    assert row.integer("probe_bytes") is None
    assert row.get("probe_bytes") is None
    assert row.boolean("api_sufficient") is None


def test_number_and_boolean_parsing() -> None:
    row = _row(probe_bytes="262,144", api_sufficient="true", full_file_size="1000")
    assert row.integer("probe_bytes") == 262144
    assert row.boolean("api_sufficient") is True
    assert row.number("full_file_size") == 1000.0


def test_manifest_round_trip(tmp_path) -> None:
    rows = [
        _row(study_accession="GCST1", trait="migraine", predicted_header="CHR\tPOS"),
        _row(study_accession="GCST2", trait="asthma"),
    ]
    path = tmp_path / "manifest.csv"
    write_manifest(rows, path)
    loaded = read_manifest(path)
    assert [r.accession for r in loaded] == ["GCST1", "GCST2"]
    assert loaded[0].header("predicted_header") == ("CHR", "POS")


def test_read_missing_manifest_raises(tmp_path) -> None:
    with pytest.raises(FileNotFoundError):
        read_manifest(tmp_path / "absent.csv")


# ----------------------------------------------------------------------
# Validation, including the circularity guard
